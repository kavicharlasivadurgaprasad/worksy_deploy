-- Provider-set service prices + real completion timestamp.
-- Purely additive and idempotent: no existing row is deleted, rewritten or "back-filled with guesses".
--
-- 1) bookings.completed_at
--      Set by the application at the moment a booking is genuinely moved IN_PROGRESS -> COMPLETED.
--      NULL for every booking that is not completed AND for bookings that were completed before this
--      column existed (their true completion time was never recorded and is deliberately NOT invented).
--
-- 2) provider_service_prices
--      One row per (provider, service) = the price THAT provider charges for THAT service.
--      There is intentionally NO default / back-fill: a provider with no row has "Price not set" and
--      cannot be booked for that service until they set a price. bookings.base_price (which already
--      snapshots the price at booking time) is untouched, so existing bookings keep their agreed price.
--
-- 3) services.price becomes nullable
--      The old single catalogue price is no longer used for pricing or booking. The column and its
--      existing values are kept (nothing is dropped) but new catalogue entries need not carry one.

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS completed_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS provider_service_prices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT         NOT NULL REFERENCES provider_profiles (id) ON DELETE CASCADE,
    service_id  BIGINT         NOT NULL REFERENCES services (id) ON DELETE CASCADE,
    price       NUMERIC(10, 2) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_provider_service_price UNIQUE (provider_id, service_id),
    CONSTRAINT chk_provider_service_price_positive CHECK (price > 0)
);

CREATE INDEX IF NOT EXISTS idx_provider_service_prices_service ON provider_service_prices (service_id);
CREATE INDEX IF NOT EXISTS idx_bookings_provider_status ON bookings (provider_id, status);

ALTER TABLE services ALTER COLUMN price DROP NOT NULL;
