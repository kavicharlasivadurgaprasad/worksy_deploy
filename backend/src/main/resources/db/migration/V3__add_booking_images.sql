-- Photos a customer attaches to a booking (problem pictures for the provider).
-- Only metadata + a storage key live in Postgres; the image bytes live in the configured
-- ImageStorage (local disk by default, see app.storage.*). Deleting a booking removes its rows.

CREATE TABLE IF NOT EXISTS booking_images (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id        BIGINT        NOT NULL REFERENCES bookings (id) ON DELETE CASCADE,
    storage_key       VARCHAR(255)  NOT NULL,
    original_filename VARCHAR(255)  NOT NULL,
    content_type      VARCHAR(50)   NOT NULL,
    size_bytes        BIGINT        NOT NULL,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_booking_images_storage_key UNIQUE (storage_key)
);

CREATE INDEX IF NOT EXISTS idx_booking_images_booking_id ON booking_images (booking_id);
