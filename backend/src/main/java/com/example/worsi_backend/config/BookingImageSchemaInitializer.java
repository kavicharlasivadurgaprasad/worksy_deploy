package com.example.worsi_backend.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.InitializingBean;
import org.springframework.jdbc.core.JdbcTemplate;

import javax.sql.DataSource;
import java.util.List;

/**
 * Safety net for the booking-photo schema, same idea as PasswordResetSchemaInitializer. It runs
 * BEFORE Hibernate validates the schema (see PasswordResetSchemaConfig) and idempotently creates
 * booking_images if it is missing. The statements mirror db/migration/V3__add_booking_images.sql
 * and use IF NOT EXISTS, so they are harmless when Flyway has already applied that migration.
 */
public class BookingImageSchemaInitializer implements InitializingBean {

    private static final Logger log = LoggerFactory.getLogger(BookingImageSchemaInitializer.class);

    private static final List<String> STATEMENTS = List.of(
            "CREATE TABLE IF NOT EXISTS booking_images ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "booking_id BIGINT NOT NULL REFERENCES bookings (id) ON DELETE CASCADE, "
                    + "storage_key VARCHAR(255) NOT NULL, "
                    + "original_filename VARCHAR(255) NOT NULL, "
                    + "content_type VARCHAR(50) NOT NULL, "
                    + "size_bytes BIGINT NOT NULL, "
                    + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, "
                    + "CONSTRAINT uk_booking_images_storage_key UNIQUE (storage_key))",
            "CREATE INDEX IF NOT EXISTS idx_booking_images_booking_id ON booking_images (booking_id)"
    );

    private final JdbcTemplate jdbc;

    public BookingImageSchemaInitializer(DataSource dataSource) {
        this.jdbc = new JdbcTemplate(dataSource);
    }

    @Override
    public void afterPropertiesSet() {
        for (String sql : STATEMENTS) {
            try {
                jdbc.execute(sql);
            } catch (Exception e) {
                log.warn("Booking-image schema step skipped: {}", e.getMessage());
            }
        }
        log.info("Booking-image schema check completed.");
    }
}
