package com.example.worsi_backend.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.InitializingBean;
import org.springframework.jdbc.core.JdbcTemplate;

import javax.sql.DataSource;
import java.util.List;

/**
 * Safety net for provider-set pricing and the booking completion timestamp, same idea as
 * ProviderLocationSchemaInitializer. It runs BEFORE Hibernate validates the schema (see
 * PasswordResetSchemaConfig) and idempotently applies the same statements as
 * db/migration/V6__provider_pricing_and_completion.sql, so it is harmless when Flyway has applied
 * (or later applies) that migration.
 *
 * Purely additive: no rows are deleted or rewritten, no price is invented for any provider, and no
 * completion time is invented for any booking.
 */
public class ProviderPricingSchemaInitializer implements InitializingBean {

    private static final Logger log = LoggerFactory.getLogger(ProviderPricingSchemaInitializer.class);

    private static final List<String> STATEMENTS = List.of(
            "ALTER TABLE bookings ADD COLUMN IF NOT EXISTS completed_at TIMESTAMP WITH TIME ZONE",
            "CREATE TABLE IF NOT EXISTS provider_service_prices ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "provider_id BIGINT NOT NULL REFERENCES provider_profiles (id) ON DELETE CASCADE, "
                    + "service_id BIGINT NOT NULL REFERENCES services (id) ON DELETE CASCADE, "
                    + "price NUMERIC(10, 2) NOT NULL, "
                    + "created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, "
                    + "updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, "
                    + "CONSTRAINT uk_provider_service_price UNIQUE (provider_id, service_id), "
                    + "CONSTRAINT chk_provider_service_price_positive CHECK (price > 0))",
            "CREATE INDEX IF NOT EXISTS idx_provider_service_prices_service ON provider_service_prices (service_id)",
            "CREATE INDEX IF NOT EXISTS idx_bookings_provider_status ON bookings (provider_id, status)",
            "ALTER TABLE services ALTER COLUMN price DROP NOT NULL"
    );

    private final JdbcTemplate jdbc;

    public ProviderPricingSchemaInitializer(DataSource dataSource) {
        this.jdbc = new JdbcTemplate(dataSource);
    }

    @Override
    public void afterPropertiesSet() {
        for (String sql : STATEMENTS) {
            try {
                jdbc.execute(sql);
            } catch (Exception e) {
                log.warn("Provider-pricing schema step skipped: {}", e.getMessage());
            }
        }
        log.info("Provider-pricing schema check completed.");
    }
}
